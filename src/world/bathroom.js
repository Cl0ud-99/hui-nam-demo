import { CapsuleGeometry, CylinderGeometry, DoubleSide, Group, Mesh, MeshBasicMaterial, MeshStandardMaterial, PlaneGeometry, PointLight, SphereGeometry, TorusGeometry } from 'three';
import { M } from '../core/materials.js';
import { sticker } from '../core/props.js';
import { box, cyl, planeGeo, rand } from '../core/util.js';
import { APT, BATH } from './apartment.js';
export { buildBathroom };

function buildBathroom(W) {
  const { x0, x1, z0, z1 } = BATH;
  const y0 = APT.y0, h = 2.6, cy = y0 + h;
  const g = new Group();
  W.root.add(g);
  const cx = (x0 + x1) / 2, cz = (z0 + z1) / 2;
  const floorMat = M.floorBath.clone();
  W.wetFloor(floorMat, { room: "bath", amount: 0.7, distortion: 0.014, tint: 14674146 });
  const floor = new Mesh(planeGeo(x1 - x0, z1 - z0), floorMat);
  floor.rotation.x = -Math.PI / 2;
  floor.position.set(cx, y0 + 8e-3, cz);
  floor.receiveShadow = true;
  g.add(floor);
  W.upperHide.push(floor);
  const ceil = new Mesh(planeGeo(x1 - x0, z1 - z0), M.ceilingDirty);
  ceil.rotation.x = Math.PI / 2;
  ceil.position.set(cx, cy, cz);
  g.add(ceil);
  const north = new Mesh(planeGeo(x1 - x0, h), M.tileWallDirty);
  north.position.set(cx, y0 + h / 2, z0);
  north.receiveShadow = true;
  g.add(north);
  W.colliders.push({ minX: x0, maxX: x1, minZ: z0 - 0.1, maxZ: z0 + 0.1, minY: y0, maxY: cy, enabled: true });
  const south = new Mesh(planeGeo(x1 - x0, h), M.tileWallDirty);
  south.rotation.y = Math.PI;
  south.position.set(cx, y0 + h / 2, z1);
  south.receiveShadow = true;
  g.add(south);
  W.colliders.push({ minX: x0, maxX: x1, minZ: z1 - 0.1, maxZ: z1 + 0.1, minY: y0, maxY: cy, enabled: true });
  const east = new Mesh(planeGeo(z1 - z0, h), M.tileWallDirty);
  east.rotation.y = -Math.PI / 2;
  east.position.set(x1, y0 + h / 2, cz);
  east.receiveShadow = true;
  g.add(east);
  W.colliders.push({ minX: x1 - 0.1, maxX: x1 + 0.1, minZ: z0, maxZ: z1, minY: y0, maxY: cy, enabled: true });
  const band = new Mesh(planeGeo(x1 - x0, 0.9), M.tileWallBlue);
  band.position.set(cx, y0 + 0.45, z0 + 0.012);
  g.add(band);
  const band2 = new Mesh(planeGeo(x1 - x0, 0.9), M.tileWallBlue);
  band2.rotation.y = Math.PI;
  band2.position.set(cx, y0 + 0.45, z1 - 0.012);
  g.add(band2);
  const sink = new Group();
  sink.position.set(2.45, y0, z0 + 0.3);
  g.add(sink);
  const basin = new Mesh(new CylinderGeometry(0.23, 0.13, 0.1, 24, 1, true), M.porcelain);
  basin.scale.x = 1.2;
  basin.position.y = 0.8;
  sink.add(basin);
  const rimT = new Mesh(new TorusGeometry(0.23, 0.018, 6, 26), M.porcelain);
  rimT.rotation.x = Math.PI / 2;
  rimT.scale.x = 1.2;
  rimT.position.y = 0.85;
  sink.add(rimT);
  const inner = new Mesh(new CylinderGeometry(0.2, 0.12, 0.09, 22), new MeshStandardMaterial({ color: 9407872, roughness: 0.35 }));
  inner.scale.x = 1.2;
  inner.position.y = 0.795;
  sink.add(inner);
  sink.add(box(0.58, 0.06, 0.42, M.porcelain, 0, 0.755, 0));
  sink.add(cyl(0.05, 0.05, 0.5, M.porcelain, 10).translateY(0.52).translateZ(0.02));
  sink.add(cyl(0.012, 0.012, 0.16, M.metalGalv, 6).translateY(0.94).translateZ(-0.06));
  const tap = new Group();
  tap.position.set(0, 0.96, -0.16);
  sink.add(tap);
  tap.add(cyl(0.012, 0.012, 0.18, M.metalGalv, 8).rotateX(Math.PI / 2).translateZ(0.09));
  tap.add(cyl(0.012, 0.012, 0.1, M.metalGalv, 8).translateY(-0.05));
  const water = new Mesh(new CylinderGeometry(35e-4, 5e-3, 0.22, 6, 1, true), M.glass);
  water.position.set(0, 0.86, 0.02);
  tap.add(water);
  tap.add(cyl(0.018, 0.018, 0.02, M.metalGalv, 8).translateY(0.03).translateZ(-0.02));
  sink.add(cyl(0.03, 0.03, 0.3, M.metalRust, 8).translateY(0.25).translateZ(-0.12));
  sink.add(cyl(0.03, 0.03, 0.26, M.metalRust, 8).rotateX(Math.PI / 2).translateY(0.12).translateZ(0));
  W.colliders.push({ minX: 2.1, maxX: 2.8, minZ: z0, maxZ: z0 + 0.5, minY: y0, maxY: y0 + 1, enabled: true });
  W.colliders.push({ minX: 2.12, maxX: 2.78, minZ: z0 + 0.02, maxZ: z0 + 0.68, minY: y0, maxY: y0 + 1, enabled: true });
  const mirror = W.makeMirror({ width: 0.66, height: 0.88, x: 2.45, y: y0 + 1.32, z: z0 + 0.045, ry: 0, room: "bath" });
  g.add(box(0.8, 0.05, 0.08, M.metalGalv, 2.45, y0 + 1.82, z0 + 0.1));
  const mTube = new Mesh(new CylinderGeometry(0.014, 0.014, 0.7, 8), M.tube);
  mTube.rotation.z = Math.PI / 2;
  mTube.position.set(2.45, y0 + 1.79, z0 + 0.12);
  g.add(mTube);
  W.addLight("bath", (() => {
    const l2 = new PointLight(16767408, 6, 3.2, 2);
    l2.position.set(2.45, y0 + 1.72, z0 + 0.24);
    return l2;
  })());
  g.add(mirror.group);
  const toilet = new Group();
  toilet.position.set(3.55, y0, 4.85);
  toilet.rotation.y = -Math.PI / 2;
  g.add(toilet);
  toilet.add(box(0.36, 0.42, 0.5, M.porcelain, 0, 0.21, 0.05));
  const bowl = new Mesh(new CylinderGeometry(0.19, 0.14, 0.16, 18), M.porcelain);
  bowl.position.set(0, 0.42, 0.16);
  bowl.scale.z = 1.25;
  toilet.add(bowl);
  const seat = new Mesh(new TorusGeometry(0.17, 0.028, 6, 18), M.porcelain);
  seat.rotation.x = Math.PI / 2;
  seat.scale.z = 1.25;
  seat.position.set(0, 0.51, 0.16);
  toilet.add(seat);
  toilet.add(box(0.44, 0.52, 0.16, M.porcelain, 0, 0.68, -0.24));
  toilet.add(box(0.4, 0.04, 0.14, M.porcelain, 0, 0.94, -0.24));
  toilet.add(cyl(0.02, 0.02, 0.02, M.metalGalv, 8).translateY(0.93).translateZ(-0.18));
  W.colliders.push({ minX: 3.1, maxX: 3.95, minZ: 4.35, maxZ: 5.25, minY: y0, maxY: y0 + 0.9, enabled: true });
  const sh = new Group();
  sh.position.set(2.15, y0, z1 - 0.06);
  sh.rotation.y = Math.PI;
  g.add(sh);
  sh.add(cyl(0.014, 0.014, 1, M.metalGalv, 8).translateY(1.65).translateZ(0.02));
  sh.add(cyl(0.014, 0.014, 0.28, M.metalGalv, 8).rotateX(Math.PI / 2).translateY(2.15).translateZ(0.14));
  const head = new Mesh(new CylinderGeometry(0.1, 0.075, 0.05, 16), M.metalGalv);
  head.position.set(0, 2.1, 0.27);
  sh.add(head);
  for (let i = 0; i < 12; i++) {
    const a = i / 12 * Math.PI * 2;
    sh.add(cyl(2e-3, 2e-3, 0.2, M.glass, 3).translateX(Math.cos(a) * 0.05).translateY(1.98).translateZ(0.27 + Math.sin(a) * 0.05));
  }
  const curtainM = new MeshStandardMaterial({ color: 11056294, roughness: 0.5, transparent: true, opacity: 0.45, side: DoubleSide, envMapIntensity: 0.6 });
  const pc = new Mesh(new PlaneGeometry(1.05, 1.55, 16, 8), curtainM);
  const pp = pc.geometry.attributes.position;
  for (let i = 0; i < pp.count; i++) pp.setZ(i, Math.sin(pp.getX(i) * 12) * 0.03);
  pc.geometry.computeVertexNormals();
  pc.position.set(2.1, y0 + 1.35, z1 - 0.18);
  g.add(pc);
  g.add(cyl(0.01, 0.01, 1.1, M.metalGalv, 6).rotateZ(Math.PI / 2).translateX(2.1).translateY(y0 + 2.12).translateZ(z1 - 0.18));
  g.add(cyl(0.06, 0.06, 6e-3, M.metalRust, 12).translateX(2.1).translateY(y0 + 0.012).translateZ(4.9));
  for (let i = 0; i < 5; i++) g.add(box(0.1, 4e-3, 6e-3, M.blackMetal, 2.1, y0 + 0.016, 4.86 + i * 0.018));
  const wh = new Group();
  wh.position.set(x1 - 0.12, y0 + 1.55, 3.4);
  wh.rotation.y = -Math.PI / 2;
  g.add(wh);
  wh.add(box(0.4, 0.5, 0.18, M.enamelWhite, 0, 0, 0));
  wh.add(cyl(8e-3, 8e-3, 0.36, M.metalGalv, 5).translateY(-0.4));
  wh.add(cyl(8e-3, 8e-3, 0.36, M.metalGalv, 5).translateX(0.06).translateY(-0.4));
  wh.add(box(0.12, 0.05, 0.02, M.blackMetal, 0.06, 0.18, 0.1));
  const ledG = new Mesh(new SphereGeometry(8e-3, 6, 5), M.bulbRed);
  ledG.position.set(-0.05, 0.18, 0.1);
  wh.add(ledG);
  g.add(box(0.5, 0.03, 0.16, M.metalRust, 3.3, y0 + 1.75, z1 - 0.12));
  for (let i = 0; i < 3; i++) {
    const b = cyl(0.03, 0.03, 0.12, [M.plasticGreen, M.enamelWhite, M.plasticBlue][i], 10);
    b.position.set(3.15 + i * 0.13, y0 + 1.82, z1 - 0.12);
    g.add(b);
  }
  const bk = new Mesh(new CylinderGeometry(0.16, 0.13, 0.3, 16, 1, true), M.plasticRed);
  bk.position.set(2, y0 + 0.15, 3.55);
  g.add(bk);
  const towel = new Mesh(new PlaneGeometry(0.34, 0.6, 6, 10), M.fabricCream);
  const tp = towel.geometry.attributes.position;
  for (let i = 0; i < tp.count; i++) tp.setZ(i, Math.sin(tp.getY(i) * 8) * 0.012);
  towel.geometry.computeVertexNormals();
  towel.position.set(2.9, y0 + 1.35, z1 - 0.1);
  g.add(towel);
  for (let i = 0; i < 8; i++) {
    const s = sticker("mold", rand(0.3, 0.8), rand(0.3, 0.8), rand(0.2, 0.5));
    s.position.set(rand(x0 + 0.1, x1 - 0.1), rand(y0 + 0.2, y0 + 2.2), rand(z0 + 0.2, z1 - 0.2));
    s.rotation.y = rand(0, Math.PI * 2);
    s.rotation.x = -Math.PI / 2;
    g.add(s);
  }
  for (let i = 0; i < 6; i++) {
    const s = sticker("stain", rand(0.3, 0.7), rand(0.4, 1.1), rand(0.2, 0.4));
    s.position.set(rand(x0 + 0.2, x1 - 0.2), rand(y0 + 0.8, y0 + 2.4), z1 - 0.015);
    s.rotation.y = Math.PI;
    g.add(s);
  }
  g.add(box(5e-3, 0.8, 2e-3, M.dirt, 2.9, y0 + 1.8, z0 + 0.02));
  const tube2 = new Mesh(new CylinderGeometry(0.016, 0.016, 0.9, 10), M.tubeGreen);
  tube2.rotation.z = Math.PI / 2;
  tube2.position.set(2.5, cy - 0.12, cz);
  g.add(tube2);
  g.add(box(1, 0.06, 0.12, M.metalDark, 2.5, cy - 0.07, cz));
  const l = W.addLight("bath", (() => {
    const p = new PointLight(13625048, 14, 4.2, 2);
    p.position.set(2.5, cy - 0.3, cz);
    return p;
  })());
  W.flicker(l, { min: 0.25, max: 1, speed: 3.4, pattern: "tube" });
  const ghost = new Group();
  const gm = new MeshBasicMaterial({ color: 329482, transparent: true, opacity: 0.92, depthWrite: false });
  const bodyG = new Mesh(new CapsuleGeometry(0.19, 0.9, 6, 10), gm);
  bodyG.position.y = 1.05;
  ghost.add(bodyG);
  const headG = new Mesh(new SphereGeometry(0.115, 14, 12), gm);
  headG.position.y = 1.72;
  ghost.add(headG);
  const hairG = new Mesh(new SphereGeometry(0.12, 14, 12), gm);
  hairG.scale.set(1, 1.35, 0.9);
  hairG.position.set(0, 1.7, -0.02);
  ghost.add(hairG);
  ghost.position.set(x0 + 0.25, y0, 4.3);
  ghost.rotation.y = 0.6;
  ghost.visible = false;
  ghost.layers.set(2);
  ghost.traverse((o) => o.layers.set(2));
  W.root.add(ghost);
  W.room("bath", { x0, x1, z0, z1, y0 });
  W.onEnter("bath", () => W.audio?.setAmbience("bath"));
  W.onEnter("bath", () => W.hud.room("\u6D74\u5BA4"));
  return { mirror, ghost, tap, water };
}
